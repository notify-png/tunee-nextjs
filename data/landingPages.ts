export const BASE_URL = "https://www.tunee.ai/music-generator";

/** Build a flat lookup: url-slug → { label, category, url } */
export function getAllItems() {
  return categories.flatMap((cat) =>
    cat.items.map((item) => ({ ...item, category: cat.label, categorySlug: cat.slug }))
  );
}

export function findItemBySlug(slug: string) {
  for (const cat of categories) {
    const item = cat.items.find((i) => i.slug === slug);
    if (item) return { ...item, category: cat.label, categorySlug: cat.slug };
  }
  return null;
}

export function formatLabel(slug: string): string {
  return slug
    .split("-")
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ");
}
